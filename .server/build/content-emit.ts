import { writeFile } from "node:fs/promises"
import { isDeepStrictEqual } from "node:util"
import type { ContentBundle, Item } from "../src/types/content"

type JsonObject = Record<string, unknown>

/**
 * JSON-LD properties used as an item's sort date, in order of preference.
 * Events carry `startDate`; articles and works carry `datePublished`.
 */
const DATE_KEYS = ["startDate", "datePublished"]

/**
 * Reads the sort date from an item's JSON-LD.
 *
 * @param item - Content item holding the JSON-LD.
 * @returns The first string value among `DATE_KEYS`, or `null` if none.
 */
function dateOf(item: { jsonld: unknown }): string | null {
  const jsonld = item.jsonld as JsonObject | null
  for (const key of DATE_KEYS) {
    const value = jsonld?.[key]
    if (typeof value === "string") return value
  }
  return null
}

/**
 * Sorts items newest first, with undated items last and ties broken by `id`.
 *
 * The order is fixed at build time so it never depends on filesystem
 * enumeration order or a database engine's tie-breaking. Dates are compared as
 * strings, which is correct for ISO 8601 (`YYYY-MM-DD`).
 *
 * @param items - Items to sort. The input array is not mutated.
 * @returns A new, sorted array.
 */
function sortByDateDesc<T extends { id: string; jsonld: unknown }>(
  items: T[],
): T[] {
  return [...items].sort((a, b) => {
    const da = dateOf(a)
    const db = dateOf(b)
    if (da !== db) {
      // Undated items go last (same as NULLs in `ORDER BY ... DESC` on SQLite)
      if (da === null) return 1
      if (db === null) return -1
      return da < db ? 1 : -1
    }
    // Same date: ascending id keeps the result deterministic
    return a.id < b.id ? -1 : a.id > b.id ? 1 : 0
  })
}

/**
 * Writes all parsed content as a single TypeScript module that the Worker
 * imports (`src/content.gen.ts`).
 *
 * Replaces the former SQLite database. The output is a pure function of the
 * repository contents (no timestamps or other build-time state), so the same
 * commit always generates the same module.
 *
 * @param outPath - Destination file path of the generated module.
 * @param items - Parsed items.
 * @throws If the serialized payload does not round-trip to the input content.
 */
export async function emitContent(
  outPath: string,
  items: Item[],
): Promise<void> {
  // The list is stored pre-sorted so the runtime only has to slice it
  const bundle: ContentBundle = { items: sortByDateDesc(items) }

  // Double stringify: the inner call yields the JSON, the outer one turns it
  // into a correctly escaped JS string literal (quotes, backslashes, newlines,
  // backticks and ${ in body_html are all safe).
  const payload = JSON.stringify(JSON.stringify(bundle))
  // Embedding a JSON string and parsing it at startup is faster than a large
  // object literal, which matters for the Worker's 1s startup budget
  const source = [
    "// Generated by build/content-emit.ts. Do not edit.",
    `import type { ContentBundle } from "./types/content"`,
    `export default JSON.parse(${payload}) as ContentBundle`,
    "",
  ].join("\n")

  // Guard against escaping bugs: decoding the emitted literal must give back
  // exactly what we serialized
  const roundTripped = JSON.parse(JSON.parse(payload)) as ContentBundle
  if (!isDeepStrictEqual(roundTripped, bundle)) {
    throw new Error("Emitted content does not round-trip to the parsed content")
  }

  await writeFile(outPath, source)
  console.log(`Content emitted: ${items.length} items`)
}
